#!/usr/bin/env bash
# hitl-loop.sh — шаблон HITL-цикла для шагов, доступных только человеку
# (TASK-hermes-15 П.2.3, механика M8 декомпозиции mattpocock §9).
#
# Паттерн источника (skills/engineering/diagnasing-bugs/scripts/
# hitl-loop.template.sh, дата доступа 2026-11-17): «The agent runs the
# script; the user follows prompts in their terminal … capture prints
# its value back to the terminal, where the agent reads it, so capture
# observations, and leave signing in to the user as a step»; итог —
# «Captured KEY=VALUE for the agent to parse».
#
# Адаптация под «Стратега»: агент готовит скрипт под ситуацию (доступ
# к внутренним данным сервиса, подтверждение в чужой системе, пароли),
# человек выполняет шаги В СВОЁМ терминале, агент парсит KEY=VALUE.
#
# Правила (не менять при адаптации):
#   1. capture — только НАБЛЮДЕНИЯ и результаты, не секреты. Пароли,
#      токены, коды 2FA человек вводит сам в том шаге, где они нужны;
#      в capture они не попадают.
#   2. Каждый capture печатает «Captured KEY=VALUE» — этой строкой
#      агент читает результат; формат ключа — латиницей, без пробелов.
#   3. Скрипт ничего не пишет в репозиторий и не сеть в интернет:
#      человек — единственный исполнитель «своего» шага.
#   4. Шаги нумеруются; между шагами — пауза до нажатия Enter
#      (read -r), иначе человек не успевает прочитать инструкцию.
#
# Использование:
#   человек:  bash templates/hitl-loop.sh [--demo]
#   агент:    читает строки «Captured KEY=VALUE» из вывода
#
# Самопроверка механики (как в hitl-loop.template.sh у источника —
# отдельный быстрый прогон):
#   bash templates/hitl-loop.sh --demo
# Должно напечатать два демо-capture и выйти с кодом 0.

set -u

DEMO=0
[ "${1:-}" = "--demo" ] && DEMO=1

step() {
  # step «N» «инструкция человеку» — пауза до подтверждения выполнения.
  local n="$1"; shift
  echo ""
  echo "=== ШАГ ${n} (человек) ==="
  echo "$*"
  if [ "$DEMO" -eq 1 ]; then
    echo "[demo] шаг пропущен"
    return 0
  fi
  read -r -p "Выполнено? Enter — продолжить, Ctrl-C — прервать: " _
}

capture() {
  # capture KEY VALUE — печать результата для агента в машиночитаемом виде.
  local key="$1"; shift
  echo "Captured ${key}=$*"
}

# --- АДАПТАЦИЯ ПОД СИТУАЦИЮ (агент правит блок ниже) --------------------
# Пример: выгрузка когорт из внутренней системы (шаг, недоступный агенту).
if [ "$DEMO" -eq 1 ]; then
  step 1 "Демо: открой внутреннюю выгрузку и сохрани файл."
  capture demo_file "cohorts-2026-11.csv"
  step 2 "Демо: подтверди число строк выгрузки."
  capture demo_rows "7043"
else
  # ЗАПОЛНИТЬ: шаги, которые может сделать только человек.
  step 1 "Опиши шаг 1 (например: выгрузи когорты из внутренней системы)."
  capture file "ПУТЬ_К_ФАЙЛУ"
  step 2 "Опиши шаг 2 (например: сверь число строк с ожидаемым)."
  capture rows "ЧИСЛО"
fi
# --- КОНЕЦ АДАПТАЦИИ ------------------------------------------------------

echo ""
echo "HITL-цикл завершён. Агент: парси строки «Captured KEY=VALUE» выше."
exit 0
